// ============================================================
// 第 07 课 · 多文件组织：类的声明与定义分成两个文件
// ------------------------------------------------------------
// 之前所有课都是一个 .cpp 装完；真实项目不是——
// 类分成 Book.h（声明：有什么）+ Book.cpp（定义：怎么做），
// 使用者在 main 里 #include "Book.h" 就够了。
// 这也是作业实验一的硬性要求："类的声明、定义、对象生成在不同文件里"。
// 编译运行：VS 里 Ctrl+F5；或 Dev-C++ 打开本文件按 F11。
// ============================================================
#include <iostream>
#include <windows.h>
#include "Book.h"          // 自己的头文件用双引号（<> 是给系统头文件用的）
using namespace std;

int main()
{
    SetConsoleOutputCP(936);

    Book b("解忧杂货店", "9787544270878", 39.5, 320);
    b.showInfo();

    b.setPages(-5);        // 门卫应该拒收
    b.showInfo();

    cout << "ISBN 校验：" << b.checkISBN("9787544270878") << endl;
    cout << "拿到的 ISBN：" << b.getIsbn() << endl;

    return 0;
}
