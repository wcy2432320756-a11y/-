// 第 02 课 · 变量与输入
// ------------------------------------------------------------
// 上一课程序只会"说"；这一课让它会"听"——
// 把用户从键盘敲进去的内容，存进变量，再打印出来。
// 编译运行：Dev-C++ 打开后按 F11；或在 VS Code 里按 Ctrl+Shift+B。
// ============================================================

#include <iostream>
#include <string>       // ① string（一串文字）类型住在这个工具箱里
using namespace std;

int main()
{
    // ② 变量 = 贴了标签的盒子。格式： 类型 名字;
    string title;       // 装文字的盒子：书名
    double price;       // 装小数的盒子：价格
    int    pages;       // 装整数的盒子：页数

    cout << "=== 入库登记 ===" << endl;

    cout << "书名: ";
    cin >> title;       // ③ cin >> 和 cout << 方向相反：把键盘的内容"吸"进盒子

    cout << "价格: ";
    cin >> price;

    cout << "页数: ";
    cin >> pages;

    // ④ 把三个盒子里的东西拼起来打印
    cout << endl;
    cout << "登记完成：" << title << " | 价格 " << price << " 元 | " << pages << " 页" << endl;

    return 0;
}