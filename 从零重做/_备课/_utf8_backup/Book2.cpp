bool Book2::checkISBN(string s)
{
    int n = (int)s.size();
    if (n != 13) return false;

    int sum = 0;
    for (int i = 0; i < 13; i++) {
        int d = s[i] - '0';
        if (d < 0 || d > 9) return false;
        // 【空2】加权：偶数位 ×1，奇数位 ×3（看的是下标 i，不是数字 d）
        // ↓ 写两行 if/else 在这下面 ↓



    }
    return sum % 10 == 0;
}

