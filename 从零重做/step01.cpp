#include <iostream>     // ① 引入"输入/输出"工具箱，cin、cout 都住在里面
using namespace std;    // ② 让 cout 这类名字可以直接写，省掉 std:: 前缀

int main()              // ③ 每个程序都必须有 main —— 电脑从这里开始执行
{
    // ④ cout = 把东西"送到"屏幕上；<< 是传送方向；endl = 换行
    cout << "欢迎使用图书馆借阅系统" << endl;

    return 0;           // ⑤ 返回 0，告诉系统"我正常结束了"
}